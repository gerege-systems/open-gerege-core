-- Гурван хэлийг багцлагдсан гэсэн тэмдэглэгээнээс нь буцаана.
--
-- Мөрийг УСТГАХГҮЙ: оператор эдгээр хэл дээр гараар орчуулга оруулсан байж
-- болно (`translations` нь ON DELETE CASCADE-тай тул устгавал тэр ажил алдагдана).
-- Буцаах үед зөвхөн `is_builtin`-ыг арилгаж, DB-ээс нэмэгдсэн энгийн хэл болгоно —
-- тэгснээр өмнөх хувилбарын код (4 хэлтэй багц) ажиллахад overlay-гаас нь уншина.
UPDATE languages
   SET is_builtin = false,
       updated_at = now()
 WHERE code IN ('ar', 'fr', 'es');
